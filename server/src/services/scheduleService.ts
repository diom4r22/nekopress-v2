export class ScheduleService {
  private items: ScheduleItem[] = CANONICAL_SCHEDULE;

  public getItems(day?: string, platform?: string): ScheduleItem[] {
    let result = [...this.items];

    if (day && day !== 'all' && day !== 'todos') {
      result = result.filter((item) => item.day.toLowerCase() === day.toLowerCase());
    }

    if (platform && platform !== 'all' && platform !== 'todos') {
      result = result.filter((item) => item.platform.toLowerCase() === platform.toLowerCase());
    }

    return result;
  }

  public getDaySummary(): Record<string, number> {
    const summary: Record<string, number> = {
      lunes: 0,
      martes: 0,
      miercoles: 0,
      jueves: 0,
      viernes: 0,
      sabado: 0,
      domingo: 0,
      total: this.items.length,
    };

    this.items.forEach((item) => {
      if (summary[item.day] !== undefined) {
        summary[item.day]++;
      }
    });

    return summary;
  }

  public getTodayDayName(timeZone = 'Asia/Tokyo'): DayOfWeek {
    const daysMap: Record<number, DayOfWeek> = {
      0: 'domingo',
      1: 'lunes',
      2: 'martes',
      3: 'miercoles',
      4: 'jueves',
      5: 'viernes',
      6: 'sabado',
    };

    try {
      const now = new Date();
      const localDate = new Date(now.toLocaleString('en-US', { timeZone }));
      return daysMap[localDate.getDay()] || 'lunes';
    } catch {
      const day = new Date().getDay();
      return daysMap[day] || 'lunes';
    }
  }
}

export const scheduleService = new ScheduleService();
